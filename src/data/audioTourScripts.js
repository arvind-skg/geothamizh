// Generates fallback audio script dynamically for any place
export function getScriptForPlace(place, lang = 'en') {
  if (!place) return { sentences: [], fullText: '' };
  
  const id = place.id;
  if (AUDIO_TOUR_SCRIPTS[id]) {
    const list = AUDIO_TOUR_SCRIPTS[id][lang] || AUDIO_TOUR_SCRIPTS[id]['en'];
    return {
      sentences: list,
      fullText: list.join(' ')
    };
  }

  // Dynamic museum-grade fallback
  if (lang === 'ta') {
    const name = place.tamilName || place.name.split(' (')[0];
    const dist = place.district ? `${place.district} மாவட்டத்தில் அமைந்துள்ள ` : '';
    const era = place.classicalName ? `${place.classicalName} என்ற புராதன பெயரைக் கொண்ட ` : '';
    const why = place.whyItMatters || 'தமிழரின் வரலாற்றுத் தொன்மைக்கு மிகச் சிறந்த சான்றாக விளங்குகிறது.';
    
    const sentences = [
      `வணக்கம். ${dist}${era}${name} வரலாற்றுத் தலத்திற்கு உங்களை அன்புடன் வரவேற்கிறோம்.`,
      `சங்க இலக்கியங்களிலும் பழங்காலக் கல்வெட்டுகளிலும் போற்றப்படும் இந்த வரலாற்றுத் தலம், தமிழரின் கட்டிடக்கலை மற்றும் பண்பாட்டுச் சிறப்பை உலகிற்குப் பறைசாற்றுகிறது.`,
      `ஆயிரம் ஆண்டுகளுக்கும் மேலாக தலைமுறை தலைமுறையாகப் பாதுகாக்கப்பட்ட இந்நிலம், ${why}`
    ];
    return {
      sentences,
      fullText: sentences.join(' ')
    };
  }

  // English dynamic fallback
  const cleanName = place.name.split(' (')[0];
  const dist = place.district ? `located in the historic ${place.district} district,` : '';
  const why = place.whyItMatters || place.shortDescription || 'an extraordinary testament to classical Tamil heritage.';
  const sentences = [
    `Welcome to ${cleanName}, ${dist} an indispensable monument in the cultural landscape of Tamilakam.`,
    `${why}`,
    `Throughout centuries of dynastic transformation, this site has preserved the artistic, religious, and architectural genius of South Indian civilization.`
  ];
  return {
    sentences,
    fullText: sentences.join(' ')
  };
}
